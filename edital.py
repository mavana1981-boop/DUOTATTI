def chave_legada(materia, nome):
    """(grupo, assunto) atual para um nome de tópico antigo, ou None."""
    tab = LEGADO.get(materia, {})
    for k in (nome, nome.split(" — ")[0].strip()):
        if k in tab:
            i, assunto = tab[k]
            return (_g(materia, i), assunto)
    # nome igual a um assunto atual (único na matéria)
    achados = [(g, a) for g, assuntos in EDITAL.get(materia, []) for a in assuntos if a == nome]
    return achados[0] if len(achados) == 1 else None
